// Package recommend 实现推荐与排行算法。
//
// 为什么必须是纯函数：推荐口径需要随需求反复调整、全量重算、离线对比，
// 只有剔除全部 IO 才能让算法可测试、可回放、可在任意数据快照上重跑。
// 输入输出均为领域结构体，数据获取由调用方（编排服务）完成。
//
// 职责：推荐（十维加权评分 + 自适应权重回收 + 三个后处理）与排行
// （热度排序 + 周期过滤）。公式唯一权威：docs/DOMAIN_RULES.md §1/§2，
// 常量与时段表逐字遵守；与旧项目（绮梦影库 App）的语义翻译决策见
// 各函数注释（FNV-1a 替代 Java hashCode、seed=0 混合也取确定性 RNG 等）。
//
// 边界（见 docs/ARCHITECTURE.md §5）：
//   - 职责：推荐/排行算法
//   - 禁止：任何 IO（纯函数，输入输出领域结构体；也不依赖其他业务模块）
package recommend
