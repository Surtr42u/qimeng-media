-- 0025_ai_clients.up: independent AI client credentials + write audit (ADR-0057 P1).
-- Additive only: two new tables and their indexes; no existing table or index is
-- touched. Timestamps use the store-wide UTC RFC3339 millisecond format (see
-- 0001 header), so lexicographic order equals chronological order.
--
-- ai_clients separates long-lived AI executor credentials from the administrator
-- session (auth_sessions). token_hash is the SHA-256 hex of the plaintext token
-- and is the only credential form stored here; the plaintext exists once in the
-- management CLI output and is never logged or persisted. scopes_json /
-- device_ids_json are JSON arrays: unknown scope values fail closed at runtime
-- (a client row with an invalid scope never authenticates).
--
-- ai_audit is append-only and deliberately has no foreign key to ai_clients:
-- revoking (not deleting) a client must not hide historical write attribution.
-- client_id is the ai_clients.id at request time; request_id is generated by the
-- server (or echoed from X-Request-Id when the caller supplies a bounded value).

CREATE TABLE ai_clients (
    id              TEXT PRIMARY KEY,
    label           TEXT NOT NULL,
    token_hash      TEXT NOT NULL,
    scopes_json     TEXT NOT NULL DEFAULT '[]'
                        CHECK (json_valid(scopes_json)),
    device_ids_json TEXT NOT NULL DEFAULT '[]'
                        CHECK (json_valid(device_ids_json)),
    created_at      TEXT NOT NULL,
    expires_at      TEXT,
    revoked_at      TEXT,
    last_used_at    TEXT
);

-- Authentication lookup: one request token maps to at most one client.
CREATE UNIQUE INDEX idx_ai_clients_token_hash ON ai_clients (token_hash);

CREATE TABLE ai_audit (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    client_id   TEXT NOT NULL,
    method      TEXT NOT NULL,
    path        TEXT NOT NULL,
    action      TEXT NOT NULL,
    status_code INTEGER NOT NULL,
    request_id  TEXT NOT NULL,
    created_at  TEXT NOT NULL
);

-- Newest-first audit reads per client (future admin query / incident review).
CREATE INDEX idx_ai_audit_client_created
    ON ai_audit (client_id, created_at DESC, id DESC);
CREATE INDEX idx_ai_audit_created
    ON ai_audit (created_at DESC, id DESC);
